"use client";

import React, { useEffect, useMemo, useRef, useState } from "react";

/* An anatomy drawing (scripts/figures → public/figures/<name>.svg), framed
   like an instrument plate: figure number and title on top, hint and live
   readout below. The SVG is fetched when the plate nears the viewport, so its
   path data never ships in the JS bundle or the RSC payload. */

export interface FigureContext {
  svg: SVGSVGElement;
  /** writes the plate's readout (visual only; never announced per frame) */
  say: (text: string) => void;
  /** true under prefers-reduced-motion: jump to targets, no tours */
  calm: boolean;
  /** true while the plate is on screen; loops stop when it is not */
  visible: () => boolean;
  /** called whenever the plate comes back on screen */
  onShow: (fn: () => void) => void;
}

export interface FigureLive<S> {
  update?: (state: S) => void;
  destroy?: () => void;
}

const cache = new Map<string, Promise<string>>();
// Drawings below the hero wait until the loader has lifted, so injecting them
// never lands on a frame of its animation.
let release = () => {};
const gate = new Promise<void>((done) => { release = done; });
export const openFigures = () => release();
/** Fetch a drawing once; the loader awaits it so its reveal never runs over nothing. */
export const load = (name: string) => {
  if (!cache.has(name)) cache.set(name, fetch(`/figures/${name}.svg`).then((r) => (r.ok ? r.text() : "")));
  return cache.get(name)!;
};

export function Figure<S = undefined>({
  name,
  hint,
  readout,
  label,
  live,
  state,
  priority = false,
  plain = false,
  className = "",
  children,
}: {
  name: string;
  hint?: string;
  readout?: string;
  /** accessible description of the drawing (role="img") */
  label: string;
  live?: (ctx: FigureContext) => FigureLive<S>;
  state?: S;
  priority?: boolean;
  /** no plate corners, just the drawing */
  plain?: boolean;
  className?: string;
  children?: React.ReactNode;
}) {
  const root = useRef<HTMLDivElement>(null);
  const host = useRef<HTMLDivElement>(null);
  const out = useRef<HTMLSpanElement>(null);
  const ctl = useRef<FigureLive<S> | null>(null);
  const [markup, setMarkup] = useState("");
  // Stable identity: React 19 re-sets innerHTML whenever this object changes,
  // which would wipe the parts a controller has moved.
  const html = useMemo(() => ({ __html: markup }), [markup]);
  const liveRef = useRef(live);
  const stateRef = useRef(state);

  // Fetch when within ~1 screen of the viewport (or at once for the hero).
  useEffect(() => {
    const el = root.current;
    if (!el) return;
    let alive = true;
    const go = () => (priority ? load(name) : gate.then(() => load(name))).then((t) => alive && setMarkup(t));
    if (priority) { go(); return () => { alive = false; }; }
    const io = new IntersectionObserver((entries) => {
      if (entries[entries.length - 1].isIntersecting) { io.disconnect(); go(); }
    }, { rootMargin: "100% 0px" });
    io.observe(el);
    return () => { alive = false; io.disconnect(); };
  }, [name, priority]);

  // Start the live controller once the drawing is in the DOM.
  useEffect(() => {
    const svg = host.current?.querySelector("svg");
    const make = liveRef.current;
    if (!svg || !make || !root.current) return;
    let visible = false;
    const shows: (() => void)[] = [];
    const io = new IntersectionObserver((entries) => {
      visible = entries[entries.length - 1].isIntersecting;
      if (visible) shows.forEach((fn) => fn());
    }, { rootMargin: "120px 0px" });
    io.observe(root.current);
    const calm = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    ctl.current = make({
      svg: svg as SVGSVGElement,
      say: (t) => { if (out.current && out.current.textContent !== t) out.current.textContent = t; },
      calm,
      visible: () => visible,
      onShow: (fn) => shows.push(fn),
    });
    if (stateRef.current !== undefined) ctl.current.update?.(stateRef.current);
    return () => { io.disconnect(); ctl.current?.destroy?.(); ctl.current = null; };
  }, [markup]);

  useEffect(() => {
    stateRef.current = state;
    if (state !== undefined) ctl.current?.update?.(state);
  }, [state]);

  const corner = "pointer-events-none absolute k-label text-k-ink-3";
  return (
    <div ref={root} data-figure={name} className={`iso relative ${className}`}>
      <div
        ref={host}
        role="img"
        aria-label={label}
        className="relative [&_svg]:block [&_svg]:h-auto [&_svg]:w-full"
        // Same-origin drawing generated by scripts/figures; no user input.
        dangerouslySetInnerHTML={html}
      />
      {!plain && (
        <>
          {hint && <span className={`${corner} bottom-0 left-0 hidden sm:block`}>{hint}</span>}
          <span ref={out} aria-hidden className={`${corner} bottom-0 right-0 text-right tabular-nums`}>{readout}</span>
        </>
      )}
      {children}
    </div>
  );
}

/** A rAF loop that runs while `tick` returns true and the plate is visible. */
export function makeLoop(ctx: FigureContext, tick: (dt: number) => boolean) {
  let frame = 0;
  let last = 0;
  const step = (now: number) => {
    const dt = last ? Math.min((now - last) / 1000, 1 / 30) : 1 / 60;
    last = now;
    const more = tick(dt);
    frame = more && ctx.visible() ? requestAnimationFrame(step) : 0;
  };
  const kick = () => { if (!frame) { last = 0; frame = requestAnimationFrame(step); } };
  ctx.onShow(kick);
  return { kick, stop: () => { cancelAnimationFrame(frame); frame = 0; } };
}

/** Exponential follow (anatomy motion.md): tau in seconds. */
export const follow = (x: number, target: number, dt: number, tau: number, calm: boolean) => {
  if (calm) return target;
  const next = x + (target - x) * (1 - Math.exp(-dt / tau));
  return Math.abs(target - next) < 1e-3 ? target : next;
};
